#include <stdio.h>

int main() {
    printf("Коды символов: '0'=%d '9'=%d 'A'=%d 'Z'=%d 'a'=%d 'z'=%d ' '=%d\n", 
           '0', '9', 'A', 'Z', 'a', 'z', ' ');
    
    printf("Проверка последовательности:\n");
    printf("Цифры 0-9 последовательны: %s\n", ('9'-'0' == 9) ? "ДА" : "НЕТ");
    printf("Буквы A-Z последовательны: %s\n", ('Z'-'A' == 25) ? "ДА" : "НЕТ");
    printf("Буквы a-z последовательны: %s\n", ('z'-'a' == 25) ? "ДА" : "НЕТ");
    
    printf("Относительный порядок:\n");
    printf("'0' < 'A': %s\n", ('0'<'A') ? "ДА" : "НЕТ");
    printf("'A' < 'a': %s\n", ('A'<'a') ? "ДА" : "НЕТ");
    printf("'9' < 'A': %s\n", ('9'<'A') ? "ДА" : "НЕТ");
    printf("'Z' < 'a': %s\n", ('Z'<'a') ? "ДА" : "НЕТ");
    printf("Пробел < '0': %s\n", (' '<'0') ? "ДА" : "НЕТ");
    
    return 0;
} 
